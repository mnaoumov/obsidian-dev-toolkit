import { noopAsync } from '@mnaoumov/typescript-lib/function';
import {
  join,
  resolve
} from '@mnaoumov/typescript-lib/path';
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync
} from 'node:fs';
import { tmpdir } from 'node:os';
import process from 'node:process';
import {
  afterEach,
  beforeEach,
  describe,
  expect,
  it,
  vi
} from 'vitest';

import {
  BuildMode,
  cleanObsidianPluginDistFolder,
  completeObsidianPluginDistFolder,
  getObsidianPluginBanner,
  getObsidianPluginDistFolder,
  getObsidianPluginEntryPoint,
  isCssFileName,
  isObsidianPluginExternal,
  mergeCssAssets,
  OBSIDIAN_PLUGIN_EXTERNALS,
  resolveFromRoot,
  resolveObsidianPluginBuildContext
} from './obsidian-plugin-build.ts';

interface MockState {
  packageName: string | undefined;
  rootFolder: null | string;
}

interface ResolvePathFromRootParams {
  readonly path: string;
}

const state = vi.hoisted((): MockState => ({
  packageName: 'my-plugin',
  rootFolder: ''
}));

vi.mock('@mnaoumov/typescript-dev-toolkit/root', async () => {
  const { resolve: resolvePath } = await import('@mnaoumov/typescript-lib/path');
  return {
    resolvePathFromRoot: ({ path }: ResolvePathFromRootParams): null | string => state.rootFolder === null ? null : resolvePath(state.rootFolder, path)
  };
});

vi.mock('@mnaoumov/typescript-dev-toolkit/npm', () => ({
  readPackageJson: vi.fn(async () => {
    await noopAsync();
    return state.packageName === undefined ? {} : { name: state.packageName };
  })
}));

describe('obsidian-plugin-build', () => {
  beforeEach(() => {
    state.rootFolder = mkdtempSync(join(tmpdir(), 'obsidian-plugin-build-'));
    state.packageName = 'my-plugin';
  });

  afterEach(() => {
    if (state.rootFolder !== null) {
      rmSync(state.rootFolder, { force: true, recursive: true });
    }
    delete process.env['OBSIDIAN_CONFIG_FOLDER'];
  });

  function getRootFolder(): string {
    if (state.rootFolder === null) {
      throw new Error('No root folder');
    }
    return state.rootFolder;
  }

  describe('isObsidianPluginExternal', () => {
    it.each([
      'obsidian',
      'electron',
      '@codemirror/view',
      '@codemirror/view/dist/index.js',
      '@lezer/common',
      'fs',
      'fs/promises',
      'node:fs',
      'node:sqlite',
      'node:test/reporters'
    ])('treats %s as external', (moduleId) => {
      expect(isObsidianPluginExternal(moduleId)).toBe(true);
    });

    it.each([
      'obsidian-lib',
      '@codemirror/new-package',
      '@mnaoumov/obsidian-lib',
      './main.ts',
      'fflate',
      ''
    ])('bundles %s', (moduleId) => {
      expect(isObsidianPluginExternal(moduleId)).toBe(false);
    });

    it('lists the Node builtins and the modules Obsidian supplies', () => {
      expect(OBSIDIAN_PLUGIN_EXTERNALS).toContain('obsidian');
      expect(OBSIDIAN_PLUGIN_EXTERNALS).toContain('path');
    });
  });

  describe('getObsidianPluginBanner', () => {
    it('names the bundler in upper case', () => {
      expect(getObsidianPluginBanner('vite')).toBe(`/*
THIS IS A GENERATED/BUNDLED FILE BY VITE
if you want to view the source, please visit the github repository of this plugin
*/
`);
    });
  });

  describe('isCssFileName', () => {
    it.each([
      ['styles.css', true],
      ['assets/main.4f2a.CSS', true],
      ['main.js', false],
      ['css', false]
    ])('%s -> %s', (fileName, expected) => {
      expect(isCssFileName(fileName)).toBe(expected);
    });
  });

  describe('mergeCssAssets', () => {
    it('does nothing for a bundle with no CSS', () => {
      expect(mergeCssAssets([])).toEqual({ fileNamesToRemove: [], stylesCss: undefined });
    });

    it('does nothing when the one CSS file already is styles.css', () => {
      expect(mergeCssAssets([{ fileName: 'styles.css', source: 'a{}' }])).toEqual({ fileNamesToRemove: [], stylesCss: undefined });
    });

    it('renames a lone CSS file', () => {
      expect(mergeCssAssets([{ fileName: 'main.css', source: 'a{}' }])).toEqual({ fileNamesToRemove: ['main.css'], stylesCss: 'a{}' });
    });

    it('concatenates several CSS files in order, styles.css included', () => {
      expect(mergeCssAssets([
        { fileName: 'styles.css', source: 'a{}' },
        { fileName: 'chunk.css', source: 'b{}' }
      ])).toEqual({ fileNamesToRemove: ['styles.css', 'chunk.css'], stylesCss: 'a{}\nb{}' });
    });
  });

  describe('paths', () => {
    it('resolves the default output folder for each mode', () => {
      expect(getObsidianPluginDistFolder(BuildMode.Production)).toBe(resolve(getRootFolder(), 'dist/build'));
      expect(getObsidianPluginDistFolder(BuildMode.Development)).toBe(resolve(getRootFolder(), 'dist/dev'));
    });

    it('resolves the entry point', () => {
      expect(getObsidianPluginEntryPoint()).toBe(resolve(getRootFolder(), 'src/main.ts'));
    });

    it('throws outside a project', () => {
      state.rootFolder = null;
      expect(() => resolveFromRoot('dist')).toThrow('Could not resolve \'dist\' against the project root');
    });
  });

  describe('cleanObsidianPluginDistFolder', () => {
    it('empties an existing folder', async () => {
      const distFolder = join(getRootFolder(), 'dist/build');
      mkdirSync(distFolder, { recursive: true });
      writeFileSync(join(distFolder, 'stale.js'), '');

      await cleanObsidianPluginDistFolder(distFolder);

      expect(existsSync(distFolder)).toBe(true);
      expect(existsSync(join(distFolder, 'stale.js'))).toBe(false);
    });

    it('creates a missing folder', async () => {
      const distFolder = join(getRootFolder(), 'dist/dev');
      await cleanObsidianPluginDistFolder(distFolder);
      expect(existsSync(distFolder)).toBe(true);
    });
  });

  describe('completeObsidianPluginDistFolder', () => {
    it('copies the manifest and writes the HotReload marker in development', async () => {
      writeFileSync(join(getRootFolder(), 'manifest.json'), '{"id":"my-plugin"}');
      const context = await resolveObsidianPluginBuildContext({ mode: BuildMode.Development });

      await completeObsidianPluginDistFolder(context);

      expect(readFileSync(join(context.distFolder, 'manifest.json'), 'utf-8')).toBe('{"id":"my-plugin"}');
      expect(existsSync(join(context.distFolder, '.hotreload'))).toBe(true);
    });

    it('writes no HotReload marker in production, and tolerates a missing manifest', async () => {
      const context = await resolveObsidianPluginBuildContext({ mode: BuildMode.Production });

      await completeObsidianPluginDistFolder(context);

      expect(existsSync(join(context.distFolder, 'manifest.json'))).toBe(false);
      expect(existsSync(join(context.distFolder, '.hotreload'))).toBe(false);
    });

    it('tolerates a project with no root to read the manifest from', async () => {
      const distFolder = join(getRootFolder(), 'out');
      const context = { ...await resolveObsidianPluginBuildContext({ mode: BuildMode.Production }), distFolder };
      state.rootFolder = null;

      await completeObsidianPluginDistFolder(context);

      expect(existsSync(distFolder)).toBe(true);
      rmSync(distFolder, { force: true, recursive: true });
    });
  });

  describe('resolveObsidianPluginBuildContext', () => {
    it('resolves a production build', async () => {
      const context = await resolveObsidianPluginBuildContext({ mode: BuildMode.Production });
      expect(context).toEqual({
        distFolder: resolve(getRootFolder(), 'dist/build'),
        entryPoint: resolve(getRootFolder(), 'src/main.ts'),
        isProductionBuild: true,
        mainJsPath: join(resolve(getRootFolder(), 'dist/build'), 'main.js'),
        obsidianConfigFolder: '',
        pluginName: 'my-plugin'
      });
    });

    it('takes the output folder and the Obsidian config folder from the options', async () => {
      const context = await resolveObsidianPluginBuildContext({
        distFolder: 'out',
        mode: BuildMode.Development,
        obsidianConfigFolder: '/vault/config-folder'
      });
      expect(context.distFolder).toBe(resolve(getRootFolder(), 'out'));
      expect(context.isProductionBuild).toBe(false);
      expect(context.obsidianConfigFolder).toBe('/vault/config-folder');
    });

    it('reads OBSIDIAN_CONFIG_FOLDER from the .env file', async () => {
      writeFileSync(join(getRootFolder(), '.env'), 'OBSIDIAN_CONFIG_FOLDER=/from-env/config-folder\n');
      const context = await resolveObsidianPluginBuildContext({ mode: BuildMode.Development });
      expect(context.obsidianConfigFolder).toBe('/from-env/config-folder');
    });

    it('names an unnamed package', async () => {
      state.packageName = undefined;
      const context = await resolveObsidianPluginBuildContext({ mode: BuildMode.Production });
      expect(context.pluginName).toBe('(unknown)');
    });
  });
});
